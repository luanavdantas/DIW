const p = new URLSearchParams(location.search);
const id = p.get('id');
const serie = dados.series.find(s => s.id == id);
const container = document.getElementById('infos');
const img = document.createElement('img');
img.src = serie.poster;
img.referrerPolicy = "no-referrer";
container.appendChild(img);
const texto = document.createElement('div');
const nome = document.createElement('h2');
nome.textContent = `${serie.nome} (${serie.ano})`;
texto.appendChild(nome);
const nota = document.createElement('div');
nota.classList.add('nota');
nota.innerHTML = `<p>${serie.nota_imdb}</p>`;
texto.appendChild(nota);
const descricao = document.createElement('h1');
descricao.textContent = serie.descricao;
texto.appendChild(descricao);
container.appendChild(texto);
const personagens = document.querySelector('.personagens');
const filtro = dados.personagens.filter(p => p.id_serie == serie.id);
filtro.forEach(p => {
    const card = document.createElement('div');
    const foto = document.createElement('img');
    foto.src = p.foto;
    foto.referrerPolicy = "no-referrer";
    card.appendChild(foto);
    const nome = document.createElement('p');
    nome.textContent = p.nome;
    card.appendChild(nome);
    personagens.appendChild(card);
});
